@dataclass
class KBChunk:
    """One retrievable unit of college knowledge.

    ``text`` is the searchable/quotable body. ``spoken_answer`` is the
    TTS-normalised form generated by ``scripts/enrich_kb_for_voice.py`` and
    is never used for lexical matching. ``search_aliases`` are appended to
    the embedded text (and to the lexical haystack) so noisy ASR queries
    can still reach the atomic record.
    """

    chunk_id: str
    source: str
    section: str
    text: str
    qa_id: str | None = None
    kind: str = "narrative"
    kb_id: str | None = None
    category: str = "general"
    effective_session: str = EFFECTIVE_SESSION
    volatility: str = "static"
    search_aliases: list[str] = field(default_factory=list)
    spoken_answer: str | None = None

    def to_dict(self) -> dict:
        return {
            "chunk_id": self.chunk_id,
            "source": self.source,
            "section": self.section,
            "text": self.text,
            "qa_id": self.qa_id,
            "kind": self.kind,
            "kb_id": self.kb_id,
            "category": self.category,
            "effective_session": self.effective_session,
            "volatility": self.volatility,
            "search_aliases": list(self.search_aliases),
            "spoken_answer": self.spoken_answer,
        }

    @property
    def embedding_text(self) -> str:
        """Text used for the dense vector, including ASR aliases."""

        if not self.search_aliases:
            return self.text
        return self.text + "\nAliases: " + "; ".join(self.search_aliases)

    @classmethod
    def from_dict(cls, data: dict) -> "KBChunk":
        raw_aliases = data.get("search_aliases") or []
        if isinstance(raw_aliases, str):
            raw_aliases = [raw_aliases]

        return cls(
            chunk_id=str(data.get("chunk_id") or ""),
            source=str(data.get("source") or ""),
            section=str(data.get("section") or ""),
            text=str(data.get("text") or ""),
            qa_id=data.get("qa_id"),
            kind=str(data.get("kind") or "narrative"),
            kb_id=data.get("kb_id") or data.get("qa_id"),
            category=str(data.get("category") or "general"),
            effective_session=str(
                data.get("effective_session") or EFFECTIVE_SESSION
            ),
            volatility=str(data.get("volatility") or "static"),
            search_aliases=[str(alias) for alias in raw_aliases if str(alias).strip()],
            spoken_answer=(
                str(data.get("spoken_answer"))
                if data.get("spoken_answer")
                else None
            ),
        )


