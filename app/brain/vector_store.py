class HashingEmbedder:
    """Dependency-free hashed n-gram embedder.

    This is not a semantic transformer, but it is a real fixed-size dense
    representation: word unigrams/bigrams plus character n-grams are
    signed-hashed into a normalised vector. It keeps exact identifiers
    (phone numbers, IFSC codes, fees) and tolerates ASR spelling noise
    far better than the lexical scorer alone, and it needs no download.
    """

    name = HASHING_EMBEDDER_NAME

    def __init__(self, dim: int = 384) -> None:
        self.dim = max(64, int(dim))

    @staticmethod
    def _tokens(text: str) -> Iterable[tuple[str, float]]:
        lowered = (text or "").casefold()
        # Keep numeric/identifier tokens intact: 1800-180-0840, 2,56,500,
        # CNRB0018556, 49 lpa.
        words = re.findall(r"[a-z0-9][a-z0-9,./-]*", lowered)

        for word in words:
            token = word.strip(",./-")
            if len(token) < 2:
                continue
            yield token, 1.0
            compact = re.sub(r"[^a-z0-9]", "", token)
            if len(compact) >= 5:
                for size in (3, 4):
                    for index in range(len(compact) - size + 1):
                        yield compact[index : index + size], 0.25

        for left, right in zip(words, words[1:]):
            yield left + " " + right, 0.6

    def _bucket(self, token: str) -> tuple[int, float]:
        digest = hashlib.blake2b(token.encode("utf-8"), digest_size=8).digest()
        value = int.from_bytes(digest, "little")
        sign = 1.0 if (value >> 63) & 1 else -1.0
        return value % self.dim, sign

    def encode(self, texts: Sequence[str]) -> np.ndarray:
        matrix = np.zeros((len(texts), self.dim), dtype=np.float32)

        for row, text in enumerate(texts):
            for token, weight in self._tokens(text):
                bucket, sign = self._bucket(token)
                matrix[row, bucket] += sign * weight

            norm = float(np.linalg.norm(matrix[row]))
            if norm > 0:
                matrix[row] /= norm

        return matrix

    def encode_query(self, text: str) -> np.ndarray:
        return self.encode([text])[0]

    def warm_up(self) -> None:
        """Prime hashing buffers so the first live query is not slower."""

        self.encode_query("admission fee helpline")


class SentenceTransformerEmbedder:
    """Optional transformer embedder, loaded lazily from local cache."""

    def __init__(self, model_name: str = DEFAULT_EMBEDDING_MODEL, device: str = "cpu") -> None:
        from sentence_transformers import SentenceTransformer

        self.name = model_name
        self.device = device
        self._model = SentenceTransformer(model_name, device=device)
        self.dim = int(self._model.get_sentence_embedding_dimension())

    def encode(self, texts: Sequence[str]) -> np.ndarray:
        vectors = self._model.encode(
            list(texts),
            batch_size=32,
            normalize_embeddings=True,
            show_progress_bar=False,
        )
        return np.asarray(vectors, dtype=np.float32)

    def encode_query(self, text: str) -> np.ndarray:
        if "bge" in self.name.casefold():
            text = "Represent this sentence for searching relevant passages: " + text
        return self.encode([text])[0]

    def warm_up(self) -> None:
        """Run one query encode so the first live turn pays no load cost."""

        self.encode_query("admission fee helpline")


class OnnxSentenceEmbedder:
    """Optional ONNX Runtime embedder (CPU), used when optimum is installed.

    ONNX keeps ``BAAI/bge-small-en-v1.5`` inside the CPU latency budget on
    machines without a usable PyTorch build. It is entirely optional: any
    import/model failure lets the caller fall back to
    sentence-transformers or the hashed embedder.
    """

    def __init__(self, model_name: str = DEFAULT_EMBEDDING_MODEL) -> None:
        from optimum.onnxruntime import ORTModelForFeatureExtraction
        from transformers import AutoTokenizer

        self.name = model_name + "-onnx"
        self.device = "cpu"
        self._tokenizer = AutoTokenizer.from_pretrained(model_name)
        self._model = ORTModelForFeatureExtraction.from_pretrained(
            model_name,
            export=True,
            provider="CPUExecutionProvider",
        )
        self.dim = int(self._model.config.hidden_size)

    def encode(self, texts: Sequence[str]) -> np.ndarray:
        import numpy as onp

        batch = self._tokenizer(
            list(texts),
            padding=True,
            truncation=True,
            max_length=256,
            return_tensors="np",
        )
        outputs = self._model(**batch)
        hidden = onp.asarray(outputs.last_hidden_state, dtype=onp.float32)
        mask = onp.asarray(batch["attention_mask"], dtype=onp.float32)[..., None]
        summed = (hidden * mask).sum(axis=1)
        counts = onp.clip(mask.sum(axis=1), 1e-6, None)
        pooled = summed / counts
        norms = onp.linalg.norm(pooled, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        return (pooled / norms).astype(onp.float32)

    def encode_query(self, text: str) -> np.ndarray:
        if "bge" in self.name.casefold():
            text = "Represent this sentence for searching relevant passages: " + text
        return self.encode([text])[0]

    def warm_up(self) -> None:
        self.encode_query("admission fee helpline")


def _onnx_preferred() -> bool:
    value = os.environ.get("GREETO_EMBED_ONNX", "1").strip().lower()
    return value not in {"0", "false", "no", "off"}


def build_embedder(
    backend: str = "auto",
    model_name: str = DEFAULT_EMBEDDING_MODEL,
    hashing_dim: int = 384,
):
    """Create the configured embedder, falling back to hashing.

    ``backend`` may be ``auto``, ``sentence-transformers``, ``onnx`` or
    ``hashing``. An explicit ``sentence-transformers`` request raises when
    the optional dependency is missing; ``auto`` prefers ONNX when optimum
    is installed, then sentence-transformers, then the hashed n-gram
    embedder. Every transformer embedder normalises its vectors.
    """

    backend = (backend or "auto").strip().lower()

    if backend in {"hashing", "hash", "fallback"}:
        return HashingEmbedder(hashing_dim)

    if backend in {"onnx", "onnxruntime"}:
        return OnnxSentenceEmbedder(model_name)

    if backend in {"auto", "sentence-transformers", "st", "transformer"} and _onnx_preferred():
        try:
            embedder = OnnxSentenceEmbedder(model_name)
            logger.info("Using ONNX embedding backend (%s).", embedder.name)
            return embedder
        except Exception as error:  # noqa: BLE001 - optional dependency
            if backend not in {"auto"}:
                logger.info("ONNX embedding unavailable (%s); trying PyTorch.", error)

    try:
        return SentenceTransformerEmbedder(model_name)
    except Exception as error:  # noqa: BLE001 - optional dependency/model
        if backend in {"sentence-transformers", "st", "transformer", "onnx", "onnxruntime"}:
            raise
        logger.info(
            "sentence-transformers unavailable (%s); using the hashed "
            "n-gram embedder.",
            error,
        )
        return HashingEmbedder(hashing_dim)


def embedder_from_meta(meta: dict):
    """Recreate the embedder recorded in an index's metadata."""

    name = str(meta.get("embedder") or HASHING_EMBEDDER_NAME)
    dim = int(meta.get("dim") or 384)

    if name == HASHING_EMBEDDER_NAME:
        return HashingEmbedder(dim)

    if name.endswith("-onnx"):
        return OnnxSentenceEmbedder(name[: -len("-onnx")])

    return SentenceTransformerEmbedder(name)


def warm_up_embedder(embedder, query: str = "admission fee helpline") -> float:
    """Run one encode and return its wall time in milliseconds."""

    started = time.perf_counter()

    if hasattr(embedder, "warm_up"):
        embedder.warm_up()
    else:
        embedder.encode_query(query)

    return (time.perf_counter() - started) * 1000.0


