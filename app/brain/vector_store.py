def strip_citations(text: str) -> str:
    """Remove private-use citation markers from knowledge text."""

    if not text:
        return text

    cleaned = _CITATION_PATTERN.sub("", text)

    return re.sub(r"[ \t]+", " ", cleaned)


def clean_text(text: str) -> str:
    """Normalise raw institutional text for indexing.

    Strips HTML blocks/tags, SEO spam, control characters and the
    private-use citation markers that otherwise leak into the prompt.
    """

    if not text:
        return ""

    cleaned = _HTML_BLOCK_PATTERN.sub(" ", text)
    cleaned = _HTML_TAG_PATTERN.sub(" ", cleaned)
    cleaned = html.unescape(cleaned)
    cleaned = strip_citations(cleaned)
    cleaned = _CONTROL_PATTERN.sub("", cleaned)
    cleaned = cleaned.replace("\ufeff", "").replace("\u200b", "")
    cleaned = _SPAM_PATTERN.sub(" ", cleaned)

    # Keep paragraph breaks but collapse the long runs of spaces that
    # PDF/Word extraction leaves behind.
    lines = [re.sub(r"[ \t]+", " ", line).strip() for line in cleaned.splitlines()]

    return "\n".join(lines).strip()


def _split_table_row(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def tables_to_prose(text: str) -> str:
    """Convert Markdown pipe tables into spoken-friendly sentences."""

    if "|" not in text:
        return text

    output: list[str] = []
    table: list[str] = []

    def flush() -> None:
        if not table:
            return

        rows = [_split_table_row(line) for line in table]
        table.clear()

        if not rows:
            return

        headers = rows[0]
        body = [
            row
            for row in rows[1:]
            if row and not _TABLE_SEPARATOR.match("|".join(row))
        ]

        for row in body:
            pairs = []
            for index, cell in enumerate(row):
                if not cell or cell in {"-", "—"}:
                    continue
                header = headers[index] if index < len(headers) else ""
                pairs.append(
                    "%s is %s" % (header, cell) if header else cell
                )
            if pairs:
                output.append(". ".join(pairs).rstrip(".") + ".")

    for line in text.splitlines():
        if line.lstrip().startswith("|"):
            table.append(line)
        else:
            flush()
            output.append(line)

    flush()

    return "\n".join(output)


def split_sentences(text: str) -> list[str]:
    """Split prose into sentence-like units without breaking decimals."""

    candidates = [part.strip() for part in _SENTENCE_BOUNDARY.split(text) if part.strip()]

    # Repair splits caused by decimals and common abbreviations ("Rs. 500").
    result: list[str] = []
    for candidate in candidates:
        if result and re.search(
            r"(?:\b(?:rs|inr|dr|mr|mrs|ms|no|approx|e\.g|i\.e)\.|"
            r"\b\d+\.)$",
            result[-1],
            re.IGNORECASE,
        ):
            result[-1] = result[-1] + " " + candidate
        else:
            result.append(candidate)

    return result


def chunk_narrative(
    text: str,
    source: str,
    section: str,
    max_chars: int = 750,
    overlap_sentences: int = 1,
) -> list[KBChunk]:
    """Group narrative prose into sentence-bounded retrievable chunks."""

    sentences = split_sentences(text)

    chunks: list[KBChunk] = []
    current: list[str] = []
    current_len = 0

    def emit() -> None:
        nonlocal current, current_len

        body = " ".join(current).strip()

        if body:
            digest = hashlib.sha1(
                (source + "\n" + section + "\n" + body).encode("utf-8")
            ).hexdigest()[:16]
            chunks.append(
                KBChunk(
                    chunk_id="n-" + digest,
                    source=source,
                    section=section,
                    text=body,
                    kind="narrative",
                )
            )

        # Carry the last sentence into the next window for context.
        if overlap_sentences > 0 and current:
            current = current[-overlap_sentences:]
            current_len = len(" ".join(current))
        else:
            current = []
            current_len = 0

    for sentence in sentences:
        if len(sentence) > max_chars:
            # Very long PDF paragraphs: hard-wrap on word boundaries.
            words = sentence.split()
            piece: list[str] = []
            piece_len = 0
            for word in words:
                if piece_len + len(word) + 1 > max_chars and piece:
                    current.append(" ".join(piece))
                    piece = []
                    piece_len = 0
                    emit()
                piece.append(word)
                piece_len += len(word) + 1
            if piece:
                sentence = " ".join(piece)

        if current and current_len + len(sentence) + 1 > max_chars:
            emit()

        current.append(sentence)
        current_len += len(sentence) + 1

    if current:
        emit()

    # The overlap carry can leave a trailing duplicate of the last chunk.
    deduped: list[KBChunk] = []
    seen: set[str] = set()
    for chunk in chunks:
        if chunk.text in seen:
            continue
        seen.add(chunk.text)
        deduped.append(chunk)

    return deduped


def _narrative_sections(text: str, source: str) -> list[tuple[str, str]]:
    """Return (section title, body) pairs for narrative prose."""

    sections: list[tuple[str, str]] = []
    current_title = Path(source).stem.replace("_", " ").title()
    body: list[str] = []

    for line in text.splitlines():
        heading = _HEADING_PATTERN.match(line)
        if heading:
            if body:
                sections.append((current_title, "\n".join(body)))
                body = []
            current_title = heading.group(2).strip() or current_title
            continue
        body.append(line)

    if body:
        sections.append((current_title, "\n".join(body)))

    # The supplied corpus places many "2.3 ..." headings inline in one
    # long paragraph, so split those too.
    expanded: list[tuple[str, str]] = []
    for title, section_body in sections:
        pieces = re.split(
            r"(?=\b\d{1,2}\.\d{1,2}\s+"
            r"(?!(?i:lakhs?|lacs?|crores?|thousand|percent|lpa|seconds?|ms|"
            r"minutes?|hours?|days?|years?)\b)[A-Z])",
            section_body,
        )
        for piece in pieces:
            cleaned = piece.strip()
            if not cleaned:
                continue
            match = re.match(
                r"(\d{1,2}\.\d{1,2}\s+"
                r"(?!(?i:lakhs?|lacs?|crores?|thousand|percent|lpa|seconds?|ms|"
                r"minutes?|hours?|days?|years?)\b)[A-Z][^.]{0,90})",
                cleaned,
            )
            piece_title = match.group(1).strip() if match else title
            expanded.append((piece_title, cleaned))

    return expanded


VOICE_KB_FILENAME = "greeto_voice_kb.jsonl"


def _voice_record_to_chunk(record: dict, source: str) -> KBChunk | None:
    """Convert one ``greeto_voice_kb.jsonl`` row into a QA chunk."""

    kb_id, group = parse_kb_id(record.get("kb_id") or record.get("qa_id"))
    question = str(record.get("question") or "").strip()
    answer = str(record.get("answer") or "").strip()

    if not kb_id or not question or not answer:
        return None

    section = str(record.get("section") or "")
    if not section:
        # Reuse the canonical section names from the Markdown ingestion.
        section = _QA_SECTIONS.get(group or "", "College knowledge")

    aliases = record.get("search_aliases") or []
    if isinstance(aliases, str):
        aliases = [aliases]

    metadata = metadata_for(kb_id)

    return KBChunk(
        chunk_id="qa-" + kb_id.lower(),
        source=source,
        section=section,
        text="Q: %s\nA: %s" % (
            re.sub(r"\s+", " ", question),
            re.sub(r"\s+", " ", answer),
        ),
        qa_id=kb_id,
        kind="qa",
        kb_id=kb_id,
        category=str(record.get("category") or metadata["category"]),
        effective_session=str(
            record.get("effective_session") or EFFECTIVE_SESSION
        ),
        volatility=str(record.get("volatility") or metadata["volatility"]),
        search_aliases=[
            str(alias).strip()
            for alias in aliases
            if str(alias).strip()
        ]
        or metadata["search_aliases"],
        spoken_answer=(
            str(record.get("spoken_answer"))
            if record.get("spoken_answer")
            else None
        ),
    )


def load_chunks_from_voice_jsonl(raw: str, source: str) -> list[KBChunk]:
    """Parse a JSONL voice corpus, returning [] when it is not one."""

    chunks: list[KBChunk] = []

    for line in raw.splitlines():
        line = line.strip()
        if not line or not line.startswith("{"):
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            return []

        if not isinstance(record, dict):
            return []

        if not (record.get("question") and record.get("answer")):
            # A normal JSON document, not the generated voice corpus.
            return []

        chunk = _voice_record_to_chunk(record, source)
        if chunk is not None:
            chunks.append(chunk)

    return chunks


_ALIAS_MAP_CACHE: dict[str, dict[str, dict]] = {}


def load_voice_alias_map(path: str | Path) -> dict[str, dict]:
    """Return ``kb_id -> metadata`` from a voice corpus, cached by path."""

    candidate = Path(path)
    if not candidate.is_absolute():
        candidate = PROJECT_ROOT / candidate

    key = str(candidate.resolve()) if candidate.exists() else str(candidate)
    if key in _ALIAS_MAP_CACHE:
        return _ALIAS_MAP_CACHE[key]

    mapping: dict[str, dict] = {}

    if candidate.exists():
        try:
            for line in candidate.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line:
                    continue
                record = json.loads(line)
                kb_id, _ = parse_kb_id(record.get("kb_id") or record.get("qa_id"))
                if not kb_id:
                    continue
                aliases = record.get("search_aliases") or []
                if isinstance(aliases, str):
                    aliases = [aliases]
                mapping[kb_id] = {
                    "search_aliases": [str(a) for a in aliases if str(a).strip()],
                    "spoken_answer": record.get("spoken_answer"),
                    "category": record.get("category"),
                    "volatility": record.get("volatility"),
                }
        except Exception as error:  # noqa: BLE001 - optional enrichment
            logger.debug("Could not read voice alias map %s: %s", candidate, error)

    _ALIAS_MAP_CACHE[key] = mapping
    return mapping


def load_chunks_from_text(text: str, source: str) -> list[KBChunk]:
    """Turn one document's text into atomic Q&A and narrative chunks."""

    cleaned = tables_to_prose(clean_text(text))

    chunks: list[KBChunk] = []
    records = list(_QA_PATTERN.finditer(cleaned))

    for match in records:
        qa_id, question, answer = match.groups()
        question = re.sub(r"\s+", " ", question).strip()
        answer = re.sub(r"\s+", " ", answer).strip().rstrip("\n")

        # The source file places the next section heading immediately after
        # the last answer in a section ("...0840.3.7 Admission Checklist").
        # It belongs to the document structure, not to the answer.
        answer = re.sub(
            r"(?:^|(?<=[.!?]))\s*\d{1,2}(?:\.\d{1,2})?\s+[A-Z][^.!?]{3,400}$",
            "",
            answer,
        ).strip()

        # The final Q&A record is followed by the "4. ..." gap-analysis
        # section, whose prose contains decimal points that defeat the
        # generic heading pattern above.
        answer = re.sub(
            r"\s*\d{1,2}\.\s+Identified Website Knowledge Gaps.*$",
            "",
            answer,
            flags=re.DOTALL,
        ).strip()

        if not question or not answer:
            continue

        group = qa_id.split("-")[1]
        section = _QA_SECTIONS.get(group, "College knowledge")

        metadata = metadata_for(qa_id)
        normalized_kb_id = metadata.get("kb_id") or qa_id

        chunks.append(
            KBChunk(
                chunk_id="qa-" + qa_id.replace("[", "").replace("]", "").lower(),
                source=source,
                section=section,
                text="Q: %s\nA: %s" % (question, answer),
                qa_id=qa_id,
                kind="qa",
                kb_id=normalized_kb_id,
                category=metadata["category"],
                effective_session=metadata["effective_session"],
                volatility=metadata["volatility"],
                search_aliases=metadata["search_aliases"],
            )
        )

    narrative = _QA_PATTERN.sub(" ", cleaned)

    for section, body in _narrative_sections(narrative, source):
        chunks.extend(
            chunk_narrative(
                body,
                source=source,
                section=section,
            )
        )

    # Identical prose can appear in the manual and the Q&A summary; keep
    # one copy so RRF is not dominated by duplicates. Chunks that quote
    # unverified aggregator estimates are dropped entirely.
    seen: set[str] = set()
    deduped: list[KBChunk] = []
    for chunk in chunks:
        key = re.sub(r"\s+", " ", chunk.text).strip().casefold()
        if not key or key in seen:
            continue
        # Atomic Q&A answers are official even when they mention an
        # aggregator by name (for example a Collegedunia award). Only
        # narrative comparison prose is excluded.
        if chunk.kind != "qa" and (
            _UNVERIFIED_AGGREGATOR_PATTERN.search(chunk.section + " " + chunk.text)
            or _REFERENCE_ONLY_PATTERN.search(chunk.section + " " + chunk.text)
        ):
            continue
        seen.add(key)
        deduped.append(chunk)

    return deduped


def _read_optional_document(file: Path) -> str:
    """Extract text from DOCX/PDF when the optional reader is installed."""

    suffix = file.suffix.lower()

    if suffix == ".docx":
        try:
            import docx  # type: ignore
        except ImportError:
            logger.debug("python-docx not installed; skipping %s", file)
            return ""

        try:
            document = docx.Document(str(file))
            parts = [paragraph.text for paragraph in document.paragraphs]
            for table in document.tables:
                for row in table.rows:
                    cells = [cell.text.strip() for cell in row.cells]
                    if cells:
                        parts.append(" | ".join(cells))
            return "\n".join(parts)
        except Exception as error:  # noqa: BLE001 - optional reader
            logger.warning("Could not read DOCX %s: %s", file, error)
            return ""

    if suffix == ".pdf":
        try:
            from pypdf import PdfReader  # type: ignore
        except ImportError:
            logger.debug("pypdf not installed; skipping %s", file)
            return ""

        try:
            reader = PdfReader(str(file))
            return "\n".join(
                page.extract_text() or "" for page in reader.pages
            )
        except Exception as error:  # noqa: BLE001 - optional reader
            logger.warning("Could not read PDF %s: %s", file, error)
            return ""

    return ""


def load_chunks(source: str | Path) -> list[KBChunk]:
    """Load every supported document below *source* into chunks."""

    path = Path(source)
    if not path.is_absolute():
        path = PROJECT_ROOT / path

    if not path.exists():
        logger.warning("Knowledge source not found: %s", path)
        return []

    supported = _TEXT_SUFFIXES | _OPTIONAL_SUFFIXES
    files: list[Path]
    if path.is_file():
        files = [path]
    else:
        files = sorted(
            file
            for file in path.rglob("*")
            if file.is_file() and file.suffix.lower() in supported
        )

    chunks: list[KBChunk] = []
    for file in files:
        if file.suffix.lower() in _OPTIONAL_SUFFIXES:
            raw = _read_optional_document(file)
        else:
            try:
                raw = file.read_text(encoding="utf-8", errors="ignore")
            except OSError as error:  # pragma: no cover - unreadable file
                logger.warning("Could not read %s: %s", file, error)
                continue

        if not raw.strip():
            continue

        try:
            # The generated voice corpus already contains cleaned Q&A text,
            # spoken answers and ASR aliases. Parse it as records instead of
            # letting the generic text path treat JSONL as narrative prose.
            if file.suffix.lower() in {".json", ".jsonl"}:
                voice_chunks = load_chunks_from_voice_jsonl(raw, source=file.name)
                if voice_chunks:
                    chunks.extend(voice_chunks)
                    continue

            chunks.extend(load_chunks_from_text(raw, source=file.name))
        except Exception as error:  # pragma: no cover - malformed document
            logger.warning("Could not parse %s: %s", file, error)

    # Markdown, DOCX and the generated voice JSONL often contain the same
    # corpus. Collapse duplicates, but prefer the enriched record (spoken
    # answer + ASR aliases) over the raw Markdown/DOCX copy.
    def priority(chunk: KBChunk) -> tuple[int, int, int]:
        return (
            1 if chunk.kind == "qa" else 0,
            1 if chunk.spoken_answer else 0,
            len(chunk.search_aliases),
        )

    positions: dict[str, int] = {}
    unique: list[KBChunk] = []
    for chunk in chunks:
        key = re.sub(r"\s+", " ", chunk.text).strip().casefold()
        if not key:
            continue
        if key in positions:
            position = positions[key]
            if priority(chunk) > priority(unique[position]):
                unique[position] = chunk
            continue
        positions[key] = len(unique)
        unique.append(chunk)

    logger.info("Loaded %d knowledge chunks from %s", len(unique), path)
    return unique


